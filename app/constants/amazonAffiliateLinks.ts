// Utility function to get random affiliate links
export function getRandomAmazonLinks(count: number = 4): string[] {
  const links = [...AMAZON_AFFILIATE_LINKS];
  const result: string[] = [];

  for (let i = 0; i < Math.min(count, links.length); i++) {
    const randomIndex = Math.floor(Math.random() * links.length);
    result.push(links[randomIndex]);
    links.splice(randomIndex, 1); // Remove to avoid duplicates
  }

  return result;
}
